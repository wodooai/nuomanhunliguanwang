    const publicData=await call('/api/data');
    assert.equal(publicData.status,200);
    assert.equal(publicData.body.cases[0].images,undefined);
    assert.match(publicData.body.cases[0].cover,/^\/thumbs\/example\.webp\?/);
    const thumb=await fetch(base+publicData.body.cases[0].cover);
    assert.equal(thumb.status,200);
    assert.equal(thumb.headers.get('content-type').split(';')[0],'image/webp');
    assert.equal((await sharp(Buffer.from(await thumb.arrayBuffer())).metadata()).width,640);
    assert.equal((await call('/api/cases/platform/detail')).status,403);
    const register=async(name,phone,email)=>{const r=await call('/api/member/register','POST',{name,phone,email,password:'member-pass',confirmPassword:'member-pass'});assert.equal(r.status,200);return r.body};
    const a=await register('甲用户','13800000001','first@example.com');
    const b=await register('乙用户','13800000002','second@example.com');
    assert.equal(a.member.emailVerified,false);
    assert.equal((await call('/api/member/password-reset/request','POST',{email:'first@example.com'})).status,200);
    assert.equal(fs.existsSync(outbox),false,'unverified email must not receive reset code');
    assert.equal((await call('/api/member/email/request','POST',{email:'first@example.com'},a.token)).status,200);
    const bindingCode=JSON.parse(fs.readFileSync(outbox,'utf8').trim().split('\n').at(-1)).code;
    assert.equal((await call('/api/member/email/confirm','POST',{email:'first@example.com',code:'000000'},a.token)).status,400);
    assert.equal((await call('/api/member/email/confirm','POST',{email:'first@example.com',code:bindingCode},a.token)).status,200);
    assert.equal((await call('/api/member/password-reset/request','POST',{email:'first@example.com'})).status,200);
    const resetCode=JSON.parse(fs.readFileSync(outbox,'utf8').trim().split('\n').at(-1)).code;
    assert.equal((await call('/api/member/password-reset/confirm','POST',{email:'first@example.com',code:'000000',password:'new-member-pass',confirmPassword:'new-member-pass'})).status,400);
    assert.equal((await call('/api/member/password-reset/confirm','POST',{email:'first@example.com',code:resetCode,password:'new-member-pass',confirmPassword:'new-member-pass'})).status,200);
    assert.equal((await call('/api/member/me','GET',null,a.token)).status,401);
    assert.equal((await call('/api/member/login','POST',{phone:a.member.phone,password:'member-pass'})).status,401);
    assert.equal((await call('/api/cases/platform/detail','GET',null,a.token)).status,403);
    assert.equal((await call('/api/member/subscribe','POST',{},a.token)).status,404);
    assert.equal((await call('/api/member/cases/platform/download','GET',null,a.token)).status,404);
    assert.equal((await call('/api/admin/support/messages','GET',null,a.token)).status,401);
    const admin=(await call('/api/login','POST',{username:'admin',password})).body.token;
    assert(admin);
    const lookup=await call('/api/admin/partner/lookup?phone=13800000001','GET',null,admin);
    assert.equal(lookup.body.member.role,'member');
    assert.equal(lookup.body.member.adminNote,'');
    assert.equal((await call('/api/admin/members/remark','POST',{id:a.member.id,phone:a.member.phone,adminNote:'客户称呼：小甲'},b.token)).status,401);
    assert.equal((await call('/api/admin/members/remark','POST',{id:a.member.id,phone:a.member.phone,adminNote:'客户称呼：小甲'},admin)).status,200);
    assert.equal((await call('/api/admin/partner/lookup?phone=13800000001','GET',null,admin)).body.member.adminNote,'客户称呼：小甲');
    assert.equal((await call('/api/admin/members','GET',null,admin)).body.members.find(m=>m.id===a.member.id).adminNote,'客户称呼：小甲');
    assert.equal((await call('/api/admin/partner/promote','POST',{id:a.member.id,phone:a.member.phone},admin)).status,200);
    const partner=(await call('/api/member/login','POST',{phone:a.member.phone,password:'new-member-pass'})).body.token;
    assert.equal(Object.hasOwn((await call('/api/member/me','GET',null,partner)).body.member,'adminNote'),false);
    assert.equal((await call('/api/cases/platform/detail','GET',null,partner)).status,200);
    const create=title=>call('/api/save','POST',{case:{title,category:'套餐婚礼',tags:[],images:['/uploads/example.jpg'],cover:'/uploads/example.jpg'}},partner);
    const first=await create('合伙人作品 1');
    assert.equal(first.status,200);
    assert.equal(first.body.case.ownerMemberId,a.member.id);
    assert.equal((await call('/api/save','POST',{case:{id:'platform',title:'越权修改',images:[]}},partner)).status,403);
    assert.equal((await call('/api/delete','POST',{id:'platform'},partner)).status,403);
    assert.equal((await call('/api/save','POST',{case:{title:'超量图片',images:Array(13).fill('/uploads/example.jpg')}},partner)).status,400);
    assert.equal((await call('/api/save','POST',{case:{title:'联系电话 13800000003',images:[]}},partner)).status,400);
